#!/usr/bin/env python3
"""Local, auditable project memory for Riyadh Natural-20.

Commands:
  ingest  Compile checkpoint logs and GitHub Actions into Markdown.
  query   Rank and cite relevant vault notes with lexical search.
  audit   Check wikilinks, required evidence, and score-scope claims.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path


VAULT = Path(__file__).resolve().parent
REQUIRED = (
  "Home.md",
  "Decisions/Scale-Gate.md",
  "Evidence/Verified-Scores.md",
  "Submission/Checklist.md",
  "Submission/Controller-Design.md",
  "Sources/Comma-Official.md",
)


def utc_now() -> str:
  return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def load_records(repo_root: Path):
  patterns = (
    "checkpoints/autopilot-progress.jsonl",
    "checkpoints/pilot/progress.jsonl",
    "checkpoints/pilot/refined-progress.jsonl",
    "checkpoints/**/progress*.jsonl",
  )
  paths = []
  for pattern in patterns:
    paths.extend(repo_root.glob(pattern))
  unique = sorted(set(p.resolve() for p in paths if p.is_file()))
  records = []
  for path in unique:
    with path.open(encoding="utf-8") as stream:
      for line_no, line in enumerate(stream, 1):
        if not line.strip():
          continue
        record = json.loads(line)
        if record.get("status") != "completed" or "stock_cost" not in record:
          continue
        record = dict(record)
        record["_source"] = str(path.relative_to(repo_root))
        record["_line"] = line_no
        records.append(record)
  return records


def fetch_runs(repo: str, limit: int = 30):
  url = f"https://api.github.com/repos/{repo}/actions/runs?per_page={limit}"
  request = urllib.request.Request(
    url,
    headers={"Accept": "application/vnd.github+json", "User-Agent": "natural20-brain"},
  )
  with urllib.request.urlopen(request, timeout=30) as response:
    payload = json.load(response)
  return payload.get("workflow_runs", [])


def latest_by_segment(records):
  latest = {}
  for record in records:
    latest[str(record["segment"]).zfill(5)] = record
  return latest


def write_generated_results(records):
  latest = latest_by_segment(records)
  rows = []
  for segment, record in sorted(latest.items()):
    score = float(record["stock_cost"])
    previous = record.get("previous_stock_cost")
    previous_text = f"{float(previous):.6f}" if previous is not None else "—"
    parity = float(record.get("parity_delta", 0.0))
    rows.append(
      f"| {segment} | {score:.6f} | {previous_text} | "
      f"{record.get('method', 'unknown')} | {parity:.3g} | "
      f"`{record['_source']}:{record['_line']}` |"
    )
  costs = [float(r["stock_cost"]) for r in latest.values()]
  mean = sum(costs) / len(costs) if costs else float("nan")
  under = sum(c < 20 for c in costs)
  content = f"""---
type: generated-evidence
scope: per-segment-checkpoints
generated_at: {utc_now()}
verified_segments: {len(costs)}
---

# Auto Results

> [!warning] Evaluation scope
> These are deterministic stock-simulator checkpoint scores for individual segments.
> They are **not** a comma leaderboard score. Only the official 5000-segment
> `report.html` may be labeled as the submission score.

| Segment | Latest stock cost | Previous | Method | Parity delta | Evidence |
|---|---:|---:|---|---:|---|
{chr(10).join(rows)}

## Snapshot

- Verified checkpoint segments: **{len(costs)}**
- Mean over available checkpoints: **{mean:.6f}**
- Checkpoints below 20: **{under}/{len(costs)}**
- Official 5000-segment score: **not available**

See [[Evidence/Verified-Scores]] and [[Decisions/Scale-Gate]].
"""
  path = VAULT / "Experiments" / "Auto-Results.md"
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(content, encoding="utf-8")
  return latest, mean, under


def write_runs(runs):
  rows = []
  for run in runs:
    rows.append(
      "| [{name} #{number}]({url}) | {status} | {conclusion} | {created} | `{sha}` |".format(
        name=run.get("name", "workflow"), number=run.get("run_number", "?"),
        url=run.get("html_url", ""), status=run.get("status", "unknown"),
        conclusion=run.get("conclusion") or "—", created=run.get("created_at", "—"),
        sha=str(run.get("head_sha", ""))[:8],
      )
    )
  content = f"""---
type: generated-evidence
generated_at: {utc_now()}
---

# GitHub Runs

| Run | Status | Conclusion | Created (UTC) | Commit |
|---|---|---|---|---|
{chr(10).join(rows)}

This page is generated by `python knowledge/brain.py ingest`.
"""
  path = VAULT / "Evidence" / "GitHub-Runs.md"
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(content, encoding="utf-8")


