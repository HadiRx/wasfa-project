def ingest(args):
  repo_root = Path(args.repo_root).resolve()
  records = load_records(repo_root)
  latest, mean, under = write_generated_results(records)
  if args.github_repo:
    try:
      write_runs(fetch_runs(args.github_repo))
    except Exception as exc:
      print(f"WARNING: GitHub run ingestion skipped: {type(exc).__name__}: {exc}")
  update_home(latest, mean, under)
  print(f"INGEST_OK records={len(records)} latest_segments={len(latest)} mean={mean:.6f}")


def markdown_files():
  return sorted(p for p in VAULT.rglob("*.md") if ".obsidian" not in p.parts)


def tokens(text):
  return [t.casefold() for t in re.findall(r"[^\W_]{2,}", text, flags=re.UNICODE)]


def query(args):
  wanted = Counter(tokens(args.question))
  ranked = []
  for path in markdown_files():
    text = path.read_text(encoding="utf-8")
    counts = Counter(tokens(text))
    score = sum((1 + wanted[word]) * min(counts[word], 8) for word in wanted)
    if score:
      lower = text.casefold()
      positions = [lower.find(word) for word in wanted if lower.find(word) >= 0]
      pos = min(positions) if positions else 0
      start, end = max(0, pos - 180), min(len(text), pos + 420)
      snippet = re.sub(r"\s+", " ", text[start:end]).strip()
      ranked.append((score, path, snippet))
  ranked.sort(key=lambda item: (-item[0], str(item[1])))
  if not ranked:
    raise SystemExit("No matching notes.")
  for score, path, snippet in ranked[:args.limit]:
    rel = path.relative_to(VAULT).with_suffix("")
    print(f"[[{rel.as_posix()}]] score={score}\n{snippet}\n")


def note_targets():
  targets = set()
  for path in markdown_files():
    rel = path.relative_to(VAULT).with_suffix("").as_posix()
    targets.add(rel.casefold())
    targets.add(path.stem.casefold())
  return targets


def audit(args):
  errors, warnings = [], []
  for required in REQUIRED:
    if not (VAULT / required).exists():
      errors.append(f"missing required note: {required}")

  targets = note_targets()
  inbound = defaultdict(int)
  link_re = re.compile(r"\[\[([^\]]+)\]\]")
  for path in markdown_files():
    text = path.read_text(encoding="utf-8")
    for raw in link_re.findall(text):
      target = raw.split("|", 1)[0].split("#", 1)[0].strip()
      key = target.casefold()
      if key not in targets and Path(target).name.casefold() not in targets:
        errors.append(f"broken wikilink in {path.relative_to(VAULT)}: [[{raw}]]")
      else:
        inbound[key] += 1
    if re.search(r"official_submission_score:\s*(?!null\b)\S+", text):
      errors.append(f"unverified official score claim in {path.relative_to(VAULT)}")

  for path in markdown_files():
    if path.name in {"Home.md", "AGENTS.md"}:
      continue
    rel = path.relative_to(VAULT).with_suffix("").as_posix().casefold()
    if inbound[rel] == 0 and inbound[path.stem.casefold()] == 0:
      warnings.append(f"orphan note: {path.relative_to(VAULT)}")

  for item in errors:
    print(f"ERROR {item}")
  for item in warnings:
    print(f"WARNING {item}")
  print(f"AUDIT_DONE errors={len(errors)} warnings={len(warnings)} notes={len(markdown_files())}")
  if errors or (args.strict and warnings):
    raise SystemExit(1)


def main():
  parser = argparse.ArgumentParser()
  sub = parser.add_subparsers(dest="command", required=True)
  p_ingest = sub.add_parser("ingest")
  p_ingest.add_argument("--repo-root", default=VAULT.parent)
  p_ingest.add_argument("--github-repo", default="")
  p_ingest.set_defaults(func=ingest)
  p_query = sub.add_parser("query")
  p_query.add_argument("question")
  p_query.add_argument("--limit", type=int, default=5)
  p_query.set_defaults(func=query)
  p_audit = sub.add_parser("audit")
  p_audit.add_argument("--strict", action="store_true")
  p_audit.set_defaults(func=audit)
  args = parser.parse_args()
  args.func(args)


if __name__ == "__main__":
  main()
